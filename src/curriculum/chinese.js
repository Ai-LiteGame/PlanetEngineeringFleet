const makeChineseItem = (char, index) => {
  if (index === 0) return { id: 'zh-001', char: '人', word: '大人', example: '大人在修路。', tier: 1 };
  if (index === 1) return { id: 'zh-002', char: '口', word: '路口', example: '车停在路口。', tier: 1 };
  const tier = index < 200 ? 1 : index < 450 ? 2 : 3;
  const word = WORD_OVERRIDES.get(char) ?? CHARACTER_POOL.slice(index - (index % 2), index - (index % 2) + 2).join('');
  const example = char === '银'
    ? '老师用金银讲解不同的金属。'
    : `${CONTEXTS[index % CONTEXTS.length](word)} 我会写好“${char}”。`;
  return {
    id: `zh-${String(index + 1).padStart(3, '0')}`,
    char,
    word,
    example,
    tier,
  };
};

export const CHINESE_ITEMS = Object.freeze(
  CHARACTER_POOL.slice(0, 700).map(makeChineseItem),
);
